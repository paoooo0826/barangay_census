// The JSON word list is the source for both browser and database patterns.
const fs = require("node:fs"),
  path = require("node:path");
const terms = require("../src/lib/profanity-terms.json");
const normalizeTerm = (word) => word.toLowerCase().replace(/([a-z])\1+/g, "$1");
const variants = [
  ...new Set(
    terms.flatMap((word) => [
      normalizeTerm(word),
      normalizeTerm(word + "s"),
      ...(/(?:ch|sh|ss|x|z)$/.test(word) ? [normalizeTerm(word + "es")] : []),
    ]),
  ),
];
const body = variants
  .map((word) => [...word].map((c) => c + "+").join(""))
  .join("|");
const spelled = variants
  .map((word) => [...word].map((c) => c + "+").join("[[:space:]]+"))
  .join("|");
const pattern = `(^|[^a-z])(${body})($|[^a-z])`;
const sql = `-- Generated by scripts/generate-profanity-sql.cjs. Do not edit the patterns by hand.
create or replace function private.contains_profanity(p_text text) returns boolean
language plpgsql immutable set search_path='' as $moderation$
declare normalized text; words text; joined text; tokens text[]; candidate text; has_long_chunk boolean; i integer; j integer;
begin
 normalized:=lower(pg_catalog.normalize(coalesce(p_text,''),'NFKD'));
 normalized:=regexp_replace(normalized,U&'[\\0300-\\036f\\200b-\\200f\\202a-\\202e\\2060-\\206f\\feff]','','g');
 normalized:=translate(normalized,'01345789','oieastbg');
 normalized:=regexp_replace(regexp_replace(regexp_replace(normalized,'@(?=[a-z])','a','g'),'[$](?=[a-z])','s','g'),'!(?=[a-z])','i','g');
 words:=regexp_replace(normalized,'[^a-z]+',' ','g');
 joined:=regexp_replace(regexp_replace(normalized,'[^a-z[:space:]]','','g'),'[[:space:]]+',' ','g');
 if words ~ '${pattern}' or joined ~ '${pattern}' or words ~ '(^|[^a-z])(${spelled})($|[^a-z])' or words ~ '(^|[[:space:]])(p+u+t+a+n+g+|t+a+n+g+)[[:space:]]+i+n+a+(n+g+|m+o+)?($|[[:space:]])' then return true; end if;
 tokens:=regexp_split_to_array(trim(words),'[[:space:]]+');
 for i in 1..coalesce(array_length(tokens,1),0) loop
   candidate:=''; has_long_chunk:=false;
   for j in i..least(array_length(tokens,1),i+17) loop
     exit when length(tokens[j]) not between 1 and 3;
     has_long_chunk:=has_long_chunk or length(tokens[j])>2;
     candidate:=candidate||tokens[j];
     if j>i and (not has_long_chunk or j-i>=2) and candidate ~ '${pattern}' then return true; end if;
   end loop;
 end loop;
 return false;
end $moderation$;
revoke all on function private.contains_profanity(text) from public,anon,authenticated;
`;
if (require.main === module) {
  const dest = path.join(
    __dirname,
    "../supabase/migrations/20261122010100_messaging_moderation.sql",
  );
  const old = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : "";
  const at = old.indexOf("-- Preserve quoted incident evidence");
  fs.writeFileSync(dest, sql + (at >= 0 ? "\n" + old.slice(at) : ""));
}
module.exports = { sql };
